#!/usr/bin/env python3
"""Build the Orca Cloud plugin upload artifact.

Orca Cloud requires a target-OS suffix in the uploaded filename. Filament Match
is pure Python, so the upload is ``filament_match_any.py``. The code is the same
single-file build used for local installation; only the Hub metadata and the
development docstring are cleaned up.

The build fails if the version override does not replace both the PEP 723
header version and ``PLUGIN_VERSION``, or if any required Hub metadata field is
missing afterwards.

Usage:
    python3 plugin/build_hub_file.py [--version X.Y.Z] [--out PATH]
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIST = HERE / "dist" / "filament_match.py"
OUT = HERE / "hub" / "filament_match_any.py"

DESCRIPTION = (
    "Matches the filament loaded in each printer slot to your installed "
    "OrcaSlicer presets or a ready-to-use Open Filament Database profile, "
    "with optional Spoolman enrichment and per-kg price sync."
)
AUTHOR = "brotholomew"
PLUGIN_ID = "filament-match"
PLUGIN_NAME = "Filament Match"
NEW_DOCSTRING = '''"""Filament Match.

Single-file Orca Cloud build. Run it from Plugins > Run > Filament Match.
See the Orca Cloud listing for usage, Spoolman setup and limitations.
"""'''
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$")
HEADER_VERSION_RE = re.compile(r'^# version = "(.*)"$', re.MULTILINE)
PLUGIN_VERSION_RE = re.compile(r'^PLUGIN_VERSION = "(.*)"$', re.MULTILINE)
METADATA_RE = {
    "id": re.compile(r'^# id = "(.*)"$', re.MULTILINE),
    "name": re.compile(r'^# name = "(.*)"$', re.MULTILINE),
    "description": re.compile(r'^# description = "(.*)"$', re.MULTILINE),
    "author": re.compile(r'^# author = "(.*)"$', re.MULTILINE),
    "version": HEADER_VERSION_RE,
}


def _substitute(text: str, pattern: str, replacement: str, label: str) -> str:
    updated, count = re.subn(pattern, replacement, text, count=1, flags=re.MULTILINE)
    if count != 1:
        raise SystemExit("could not replace %s metadata in the single-file build" % label)
    return updated


def _metadata(text: str) -> dict[str, str]:
    values: dict[str, str] = {}
    for field, pattern in METADATA_RE.items():
        matches = pattern.findall(text)
        if len(matches) != 1 or not matches[0].strip():
            raise SystemExit(
                "generated Hub artifact must contain exactly one non-empty %s field" % field)
        values[field] = matches[0]
    return values


def _versions(text: str) -> tuple[str, str]:
    headers = HEADER_VERSION_RE.findall(text)
    plugins = PLUGIN_VERSION_RE.findall(text)
    if len(headers) != 1 or len(plugins) != 1:
        raise SystemExit(
            "single-file build must contain one header version and one PLUGIN_VERSION")
    return headers[0], plugins[0]


def build(version: str = "", out: Path | None = None) -> Path:
    version = version.strip()
    if version and not VERSION_RE.fullmatch(version):
        raise SystemExit("invalid version %r; expected a semantic version" % version)
    destination = Path(out) if out is not None else OUT

    subprocess.run([sys.executable, str(HERE / "build_single_file.py")], check=True)
    text = DIST.read_text(encoding="utf-8")
    canonical_header, canonical_plugin = _versions(text)
    if canonical_header != canonical_plugin:
        raise SystemExit(
            "source version mismatch: header has %r but PLUGIN_VERSION is %r" %
            (canonical_header, canonical_plugin))

    if version:
        text = _substitute(
            text, r'^# version = ".*"$', '# version = "%s"' % version, "version")
        text = _substitute(
            text, r'^PLUGIN_VERSION = ".*"$', 'PLUGIN_VERSION = "%s"' % version,
            "PLUGIN_VERSION")
        header, plugin = _versions(text)
        if header != version or plugin != version:
            raise SystemExit(
                "version override failed: header is %r, PLUGIN_VERSION is %r" %
                (header, plugin))

    generated_marker = (
        "# Generated by plugin/build_single_file.py — edit the source modules, "
        "not this file.\n\n"
    )
    if generated_marker not in text:
        raise SystemExit("single-file build marker is missing; regenerate the build")
    text = text.replace(generated_marker, "", 1)

    text = _substitute(
        text, r'^# description = ".*"$',
        '# description = "%s"' % DESCRIPTION.replace('"', '\\"'), "description")
    text = _substitute(
        text, r'^# author = ".*"$', '# author = "%s"' % AUTHOR, "author")
    docstring, docstring_count = re.subn(
        r'"""Filament Match\..*?"""', NEW_DOCSTRING, text, count=1, flags=re.S)
    if docstring_count != 1:
        raise SystemExit("could not replace the development docstring")
    text = docstring

    metadata = _metadata(text)
    if metadata["id"] != PLUGIN_ID:
        raise SystemExit("unexpected Hub plugin id %r" % metadata["id"])
    if metadata["name"] != PLUGIN_NAME:
        raise SystemExit("unexpected Hub plugin name %r" % metadata["name"])
    if metadata["author"] != AUTHOR:
        raise SystemExit("unexpected Hub plugin author %r" % metadata["author"])
    header, plugin = _versions(text)
    if header != metadata["version"] or plugin != metadata["version"]:
        raise SystemExit(
            "generated Hub version fields disagree: %r, %r, %r" %
            (metadata["version"], header, plugin))
    try:
        compile(text, str(destination), "exec")
    except SyntaxError as error:
        raise SystemExit("generated Hub artifact is not valid Python: %s" % error) from error

    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text, encoding="utf-8")
    return destination


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--version",
        default="",
        help="override the plugin version, e.g. from a GitHub release tag",
    )
    parser.add_argument(
        "--out",
        default="",
        help="write to this path instead of plugin/hub/filament_match_any.py",
    )
    args = parser.parse_args()
    path = build(args.version.strip(), Path(args.out) if args.out else None)
    print("wrote %s (%d bytes)" % (path, path.stat().st_size))
